def get_first_rPr(para):
    for r in para.runs:
        rPr = r._r.find(qn("w:rPr"))
        if rPr is not None:
            return copy.deepcopy(rPr)
    return None


def make_red_rPr(template_para):
    rPr = get_first_rPr(template_para)
    if rPr is not None:
        color_el = rPr.find(qn("w:color"))
        if color_el is not None:
            color_el.set(qn("w:val"), "FF0000")
        else:
            c = OxmlElement("w:color")
            c.set(qn("w:val"), "FF0000")
            rPr.append(c)
    else:
        rPr = OxmlElement("w:rPr")
        c = OxmlElement("w:color")
        c.set(qn("w:val"), "FF0000")
        rPr.append(c)
    return rPr


def insert_after(anchor_para, text, template_para):
    new_p = OxmlElement("w:p")
    pPr_src = template_para._p.find(qn("w:pPr"))
    if pPr_src is not None:
        new_p.append(copy.deepcopy(pPr_src))
    new_r = OxmlElement("w:r")
    new_r.append(make_red_rPr(template_para))
    t_el = OxmlElement("w:t")
    t_el.set(qn("xml:space"), "preserve")
    t_el.text = text
    new_r.append(t_el)
    new_p.append(new_r)
    anchor_para._p.addnext(new_p)
    return new_p


def insert_quote_after(anchor_para, text, template_para):
    """Insert a block quote paragraph (uses quote template style if available, still red)."""
    return insert_after(anchor_para, text, template_para)


def find_para(keyword):
    for i, p in enumerate(doc.paragraphs):
        if keyword in p.text:
            return i, p
    return None, None


